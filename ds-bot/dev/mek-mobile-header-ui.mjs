import assert from 'node:assert/strict'
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { resolve, join } from 'node:path'
import { chromium } from 'playwright'
const [folder, port, output] = process.argv.slice(2), home = resolve(folder), out = resolve(output)
assert.ok(home.split('/').at(-1).startsWith('.dsh-test-') && port !== '3080')
mkdirSync(out, { recursive: true })
const base = `http://127.0.0.1:${port}`, launch = readFileSync(join(home, 'web.log'), 'utf8').split(/\s+/).find(v => v.startsWith(`${base}/?token=`))
const browser = await chromium.launch({ executablePath: '/opt/google/chrome/chrome', headless: true, args: ['--no-sandbox'] })
try {
  const page = await browser.newPage({ viewport: { width: 1200, height: 900 }, reducedMotion: 'reduce' }), errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(launch)
  const welcome = page.getByRole('button', { name: '继续', exact: true })
  if (await welcome.isVisible().catch(() => false)) await welcome.click()
  await page.getByRole('button', { name: 'Bot', exact: true }).click()
  const header = page.locator('.mek-team-header'), tools = page.locator('.mek-team-tools')
  await tools.getByRole('button', { name: '搜索', exact: true }).waitFor()
  assert.equal(await tools.locator(':scope > button').count(), 4)
  await page.setViewportSize({ width: 390, height: 900 })
  await page.waitForFunction(() => document.querySelector('.mek-team-header')?.hasAttribute('data-compact'))
  assert.equal(await tools.locator(':scope > button').count(), 1)
  await tools.getByRole('button', { name: '更多', exact: true }).click()
  const menu = page.locator('.mek-team-menu')
  for (const name of ['Bot 列表', '任务', '搜索 Bot']) await menu.getByRole('menuitem', { name, exact: true }).waitFor()
  const geometry = await header.evaluate(node => ({ width: node.clientWidth, scroll: node.scrollWidth, top: node.getBoundingClientRect().top }))
  assert.ok(geometry.scroll <= geometry.width + 1)
  await page.screenshot({ path: join(out, 'mek-mobile-more-390.png') })
  await menu.getByRole('menuitem', { name: 'Bot 列表', exact: true }).click()
  await page.getByRole('dialog', { name: 'Bot 列表', exact: true }).waitFor()
  await page.keyboard.press('Escape')
  await page.getByRole('dialog', { name: 'Bot 列表', exact: true }).waitFor({ state: 'hidden' })
  await tools.getByRole('button', { name: '更多', exact: true }).click()
  await menu.getByRole('menuitem', { name: '任务', exact: true }).click()
  await page.getByRole('tab', { name: '任务', exact: true }).waitFor()
  await page.getByRole('button', { name: '关闭详情', exact: true }).click()
  await tools.getByRole('button', { name: '更多', exact: true }).click()
  await menu.getByRole('menuitem', { name: '搜索 Bot', exact: true }).click()
  await page.getByRole('dialog', { name: '搜索', exact: true }).waitFor()
  await page.keyboard.press('Escape')
  await page.getByRole('dialog', { name: '搜索', exact: true }).waitFor({ state: 'hidden' })
  await page.setViewportSize({ width: 1200, height: 900 })
  await tools.getByRole('button', { name: '搜索', exact: true }).waitFor()
  assert.equal(await tools.locator(':scope > button').count(), 4)
  assert.deepEqual(errors, [])
  writeFileSync(join(out, 'mek-mobile-more.json'), JSON.stringify({ geometry, errors, narrowButtons: 1, wideButtons: 4, listTasksSearchWork: true, sidebarHeaderNotModified: true }, null, 2))
  console.log('PASS: narrow Bot list/tasks/search live in More; all three routes work; wide shortcuts return; sidebar row unchanged.')
} catch (error) { console.error(String(error.stack ?? error).replace(/token=[^\s"']+/g, 'token=[redacted]')); process.exitCode = 1 }
finally { await browser.close() }
